export function normalizeManufacturerSearch(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]/gu, "");
}
export function searchManufacturers(category: VehicleCategory, query = "") {
  const needle = normalizeManufacturerSearch(query);
  return MANUFACTURERS.filter(
    (brand) =>
      brand.categories.includes(category) &&
      (!needle ||
        normalizeManufacturerSearch(brand.ar + brand.en + brand.id).includes(
          needle,
        )),
  );
}
export function manufacturerRequestContext(input: {
  category: VehicleCategory;
  manufacturer?: Manufacturer;
  customName?: string;
  model?: string;
  year?: string;
}) {
  const name = input.manufacturer
    ? `${input.manufacturer.ar} (${input.manufacturer.en})`
    : input.customName?.trim().slice(0, 50);
  const model = input.model?.trim().slice(0, 50);
  const year = input.year && /^\d{4}$/.test(input.year) ? input.year : "";
  if (!name && !model && !year) return "";
  const category = VEHICLE_CATEGORIES.find(
    (item) => item.id === input.category,
  )?.label;
  return (
    [
      name ? `المركبة: ${category} — ${name}` : `نوع المركبة: ${category}`,
      model ? `الطراز: ${model}` : "",
      year ? `سنة الصنع: ${year}` : "",
    ]
      .filter(Boolean)
      .join("\n") + "\n"
  );
}
